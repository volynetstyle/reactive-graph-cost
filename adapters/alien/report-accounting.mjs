// Runs the corpus on the port and regenerates research/M2-ACCOUNTING.md.
//
//   npm run alien:accounting
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "../..");
const dir = path.join(root, ".cache/alien-accounting");
mkdirSync(dir, { recursive: true });
for (const f of readdirSync(dir)) writeFileSync(path.join(dir, f), "null");

const { status } = spawnSync("npx vitest run --config adapters/alien/vitest.config.ts --reporter=dot", {
  cwd: root,
  env: { ...process.env, ALIEN_PORT: "1" },
  shell: true,
  stdio: "inherit",
});
if (status !== 0) process.exit(status ?? 1);

const rows = readdirSync(dir)
  .map((f) => JSON.parse(readFileSync(path.join(dir, f), "utf8")))
  .filter((r) => r !== null)
  .sort((a, b) => a.file.localeCompare(b.file));

const groups = [
  ["Tracking outcomes", ["linkHitPrev", "linkHitNext", "linkDedupedByRightTail", "linksAtTail", "linksInsideList", "duplicatePairBirths"]],
  ["Relation roles", ["dependencyLinks", "ownershipLinks"]],
  ["Traversal", ["forwardLeftSteps", "forwardRightSteps", "reverseWalkSteps", "isValidLinkSteps"]],
  ["Payload", ["versionReads", "versionWrites", "maxVersion"]],
  ["Removal and zero subscribers", ["unlinks", "unwatchedComputed", "unwatchedSignal", "unwatchedEffect", "unwatchedScope"]],
  ["Crossing user code", ["updateCrossings", "linksHeldAcrossUpdate", "heldLinksRetiredByUpdate", "unwatchedCrossings", "savedNextRetiredByUnwatched"]],
  ["Use of retired Links", ["retiredNextDep", "retiredNextSub", "retiredNextDivergentFromFrozen", "retiredEndpointReads", "retiredPredecessorReads", "secondUnlinks"]],
  ["Epochs", ["epochs", "maxEpochDepth", "maxSimultaneouslyRetired"]],
  ["External high-water marks", ["relationSlots", "nodes"]],
];
const shortName = (f) => f.replace(".spec.ts", "");
const lines = [
  "# M2.4 accounting",
  "",
  "Generated by `npm run alien:accounting`. Do not edit.",
  "",
  "Counts over Alien's unchanged corpus at `8734d38` on the port, per test file. Retired-Link reads include those made by the tolerated second unlink.",
  "",
];
for (const [title, keys] of groups) {
  lines.push(`## ${title}`, "", `| Counter | ${rows.map((r) => shortName(r.file)).join(" | ")} |`, `| --- | ${rows.map(() => "---:").join(" | ")} |`);
  for (const key of keys) lines.push(`| ${key} | ${rows.map((r) => r[key]).join(" | ")} |`);
  lines.push("");
}
lines.push("## Tests that touched a retired Link", "", "| Test | Counts |", "| --- | --- |");
for (const r of rows) {
  for (const t of r.touching) {
    lines.push(`| ${t.name.replaceAll("|", "\\|")} | ${Object.entries(t.counts).map(([k, v]) => `${k} ${v}`).join(", ")} |`);
  }
}
lines.push("");
writeFileSync(path.join(root, "research/M2-ACCOUNTING.md"), lines.join("\n"));
console.log(`wrote research/M2-ACCOUNTING.md from ${rows.length} files`);
