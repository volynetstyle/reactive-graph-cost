// Runs the corpus on the port and regenerates research/M1-ACCOUNTING.md.
//
//   npm run quant:accounting
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "../..");
const dir = path.join(root, ".cache/accounting");
mkdirSync(dir, { recursive: true });
for (const f of readdirSync(dir)) writeFileSync(path.join(dir, f), "null");

const { status } = spawnSync("npx vitest run --config adapters/quant/vitest.config.ts --reporter=dot", {
  cwd: root,
  env: { ...process.env, QUANT_PORT: "1" },
  shell: true,
  stdio: "inherit",
});
if (status !== 0) process.exit(status ?? 1);

const rows = readdirSync(dir)
  .map((f) => JSON.parse(readFileSync(path.join(dir, f), "utf8")))
  .filter((r) => r !== null)
  .sort((a, b) => a.file.localeCompare(b.file));

const groups = [
  ["Retired `next` and fields", ["retiredNextReads", "retiredNextReadsNonNull", "retiredNextDivergent", "retiredFieldReads", "continuationRecords", "maxSimultaneouslyRetired"]],
  ["Walks across user code", ["walkEpochs", "maxWalkDepth", "userCodeCrossings", "edgesHeldAcrossUserCode", "edgesRetiredWhileHeld"]],
  ["Backward scan", ["backwardHits", "backwardReachedHead", "backwardBudgetExhausted", "absenceProofs"]],
  ["Subscriber pair lookup", ["pairFoundFirst", "pairFoundDeeper", "pairAbsent", "pairBudgetExhausted"]],
  ["Index and sweep work", ["indexes", "indexedEdges", "sweeps"]],
  ["Structural operations", ["linksAtTail", "linksInsideList", "moves", "unlinks"]],
  ["External high-water marks", ["relationSlots", "nodes"]],
];

const shortName = (f) => f.replace(".test.ts", "");
const lines = [
  "# M1.4 accounting",
  "",
  "Generated by `npm run quant:accounting`. Do not edit.",
  "",
  "Counts over Quant's unchanged corpus at `241a3b7` on the port, per test file. `l0-walks` is the three probes W1 to W3, not Quant's corpus.",
  "",
];
for (const [title, keys] of groups) {
  lines.push(`## ${title}`, "", `| Counter | ${rows.map((r) => shortName(r.file)).join(" | ")} |`, `| --- | ${rows.map(() => "---:").join(" | ")} |`);
  for (const key of keys) lines.push(`| ${key} | ${rows.map((r) => r[key]).join(" | ")} |`);
  lines.push("");
}
writeFileSync(path.join(root, "research/M1-ACCOUNTING.md"), lines.join("\n"));
console.log(`wrote research/M1-ACCOUNTING.md from ${rows.length} files`);
