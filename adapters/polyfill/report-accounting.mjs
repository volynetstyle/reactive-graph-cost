// Runs the corpus on the port and regenerates research/M3-ACCOUNTING.md.
//
//   npm run polyfill:accounting
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "../..");
const dir = path.join(root, ".cache/polyfill-accounting");
mkdirSync(dir, { recursive: true });
for (const f of readdirSync(dir)) writeFileSync(path.join(dir, f), "null");

const { status } = spawnSync("npx vitest run --config adapters/polyfill/vitest.config.ts --reporter=dot", {
  cwd: root,
  env: { ...process.env, POLYFILL_PORT: "1" },
  shell: true,
  stdio: "inherit",
});
if (status !== 0) process.exit(status ?? 1);

const rows = readdirSync(dir).map((f) => JSON.parse(readFileSync(path.join(dir, f), "utf8"))).filter((r) => r !== null);
const MAX = new Set(["maxCascadeDepth"]);
const keys = [
  "traceWritesWithoutRelation",
  "traceEntriesAtEnd",
  "traceEntriesWithoutRelationAtEnd",
  "activations",
  "deactivations",
  "maxCascadeDepth",
  "birthsFromTrace",
  "deathsFromTrace",
  "birthsFromActivation",
  "deathsFromDeactivation",
  "rightSwaps",
  "rightTailRemovals",
  "rightWalkSteps",
];
const total = (key) => rows.reduce((sum, r) => (MAX.has(key) ? Math.max(sum, r[key]) : sum + r[key]), 0);
const lines = [
  "# M3.4 accounting",
  "",
  "Generated by `npm run polyfill:accounting`. Do not edit.",
  "",
  `Totals over the polyfill's frozen corpus at \`fba09f8\` on the port, ${rows.length} test files.`,
  "`maxCascadeDepth` is a maximum; the others are sums. End-of-file counts are taken after each file's tests.",
  "",
  "| Counter | Value |",
  "| --- | ---: |",
  ...keys.map((key) => `| ${key} | ${total(key)} |`),
  "",
];
writeFileSync(path.join(root, "research/M3-ACCOUNTING.md"), lines.join("\n"));
console.log(`wrote research/M3-ACCOUNTING.md from ${rows.length} files`);
