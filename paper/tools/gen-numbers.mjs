const must = (v, what) => {
  if (v === undefined || v === null || (typeof v === "number" && !Number.isFinite(v))) throw new Error(`missing value: ${what}`);
  return v;
};
const int = (x) => String(Math.round(must(x, "int"))).replace(/\B(?=(\d{3})+(?!\d))/g, "{,}");
const fix = (x, n) => must(x, "fix").toFixed(n);
const ns = (x) => (must(x, "ns") >= 100 ? x.toFixed(0) : x >= 10 ? x.toFixed(1) : x.toFixed(2));
const small = (x) => (must(x, "small") >= 100 ? x.toFixed(0) : x >= 10 ? x.toFixed(1) : x >= 1 ? x.toFixed(2) : x.toFixed(3));
const ratio = (x) => (must(x, "ratio") >= 100 ? x.toFixed(0) : x >= 10 ? x.toFixed(1) : x.toFixed(2));
const range = (s, f = ns) => `${f(s.median)} [${f(s.min)}, ${f(s.max)}]`;
const pass = (x) => `${int(x.same)}/${int(x.programs)}`;

const macros = new Map();
const def = (name, value) => {
  if (!/^[A-Za-z]+$/.test(name)) throw new Error(`bad macro name ${name}`);
  if (macros.has(name)) throw new Error(`duplicate macro ${name}`);
  macros.set(name, String(must(value, name)));
};
const table = (name, spec, head, rows) => {
  const body = rows.map((r) => (r === "---" ? "\\midrule" : `${r.join(" & ")} \\\\`)).join("\n");
  writeFileSync(path.join(tables, `${name}.tex`), `% Generated by paper/tools/gen-numbers.mjs. Do not edit.\n\\begin{tabular}{${spec}}\n\\toprule\n${head.join(" & ")} \\\\\n\\midrule\n${body}\n\\bottomrule\n\\end{tabular}\n`);
};
const tt = (s) => `\\texttt{${s}}`;

