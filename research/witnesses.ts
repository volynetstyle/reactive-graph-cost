// Regenerates research/WITNESSES.md: the shortest history that breaks the
// contract for each ablation, plus the bounded checks of the machine itself
// and of the controls. Takes several minutes.
//
//   npm run witnesses

import { writeFileSync } from "node:fs";
import { ABLATIONS, CONTROLS } from "../reference/ablations.ts";
import { RelationMachine } from "../reference/machine.ts";
import { formatHistory } from "../reference/run.ts";
import { DEEP_BOUNDS, WIDE_BOUNDS, WITNESS_BOUNDS, search, type Bounds } from "../reference/search.ts";

const describeBounds = (b: Bounds): string =>
  `${b.maxNodes} node(s), ${b.maxRelations} relations issued, epoch depth ${b.maxEpochDepth}`;

const lines: string[] = [
  "# Witnesses",
  "",
  "Generated by `npm run witnesses`. Do not edit.",
  "",
  `Search bound: ${describeBounds(WITNESS_BOUNDS)}, histories up to ${WITNESS_BOUNDS.maxLength} operations.`,
  "Each witness is a shortest history within that bound on which the ablated machine breaks a contract clause.",
  "A witness shows the mechanism is load-bearing for the contract; `surface` entries show only that a capability is observable.",
  "",
  "| Ablation | Removes | Evidence | Length | Clauses broken | Shortest witness |",
  "| --- | --- | --- | ---: | --- | --- |",
];

for (const ablation of ABLATIONS) {
  const { witness } = search(ablation.make, WITNESS_BOUNDS);
  console.log(`${ablation.id}: ${witness === null ? "NO WITNESS" : `${witness.ops.length} ops`}`);
  if (witness === null) {
    lines.push(`| ${ablation.id} | ${ablation.removes} | ${ablation.evidence} | - | **none found** | - |`);
    continue;
  }
  const clauses = [...new Set(witness.violations.map((v) => v.clause))].join(", ") || "(divergence only)";
  lines.push(
    `| ${ablation.id} | ${ablation.removes} | ${ablation.evidence} | ${witness.ops.length} | ${clauses} | \`${formatHistory(witness.ops)}\` |`,
  );
}

lines.push(
  "",
  "## Bounded exhaustive checks",
  "",
  "Every reachable state within the bound was checked when `Exhausted` is true.",
  "Controls change only physical choices the contract leaves open, so they must produce no witness.",
  "",
  "| Subject | Bound | Witness | States | Exhausted |",
  "| --- | --- | --- | ---: | --- |",
);

const reference = (): RelationMachine => new RelationMachine();
const control = (id: string): (() => RelationMachine) => {
  const found = CONTROLS.find((c) => c.id === id);
  if (found === undefined) throw new Error(`no control ${id}`);
  return found.make;
};
const subjects = [
  { id: "reference machine", bounds: WIDE_BOUNDS, make: reference },
  { id: "reference machine", bounds: DEEP_BOUNDS, make: reference },
  { id: "control: generation-at-allocate", bounds: WIDE_BOUNDS, make: control("generation-at-allocate") },
  { id: "control: fifo-freelist", bounds: DEEP_BOUNDS, make: control("fifo-freelist") },
];

for (const subject of subjects) {
  const result = search(subject.make, subject.bounds);
  console.log(`${subject.id}: ${result.statesExplored} states, exhausted=${result.exhausted}`);
  const found = result.witness === null ? "none" : `\`${formatHistory(result.witness.ops)}\``;
  lines.push(
    `| ${subject.id} | ${describeBounds(subject.bounds)} | ${found} | ${result.statesExplored} | ${result.exhausted} |`,
  );
}

lines.push("");
writeFileSync(new URL("./WITNESSES.md", import.meta.url), lines.join("\n"));
